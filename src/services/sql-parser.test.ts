function fieldOf(result: ReturnType<typeof parseSqlSchema>, tableName: string, fieldName: string): Field {
  const table = result.tables.find((item) => item.name === tableName);
  const field = table?.fields.find((item) => item.name === fieldName);
  if (!field) throw new Error(`No existe ${tableName}.${fieldName}`);
  return field;
}

function relationNames(result: ReturnType<typeof parseSqlSchema>): string[] {
  const tableName = (id: string) => result.tables.find((table) => table.id === id)?.name;
  const fieldName = (tableId: string, fieldId: string) =>
    result.tables.find((table) => table.id === tableId)?.fields.find((field) => field.id === fieldId)?.name;
  return result.relations.map(
    (relation) =>
      `${tableName(relation.fromTableId)}.${fieldName(relation.fromTableId, relation.fromFieldId)}->${tableName(relation.toTableId)}.${fieldName(relation.toTableId, relation.toFieldId)} ${relation.kind}`,
  );
}

describe("tokenizeSql", () => {
  it("ignora comentarios y reconoce identificadores entrecomillados", () => {
    const tokens = tokenizeSql("-- hola\nCREATE /* x */ TABLE `a``b` [c]]d] \"e\"\"f\" 'it''s' # fin");
    expect(tokens.map((token) => token.value)).toEqual(["CREATE", "TABLE", "a`b", "c]d", 'e"f', "it's"]);
  });
});

describe("parseSqlSchema — MySQL", () => {
  const sql = `
    CREATE TABLE \`users\` (
      \`id\` INT UNSIGNED NOT NULL AUTO_INCREMENT,
      \`email\` VARCHAR(190) NOT NULL,
      \`status\` ENUM('active','banned') NOT NULL DEFAULT 'active',
      \`is_admin\` TINYINT(1) NOT NULL DEFAULT 0,
      \`created_at\` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      PRIMARY KEY (\`id\`),
      UNIQUE KEY \`uq_email\` (\`email\`)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

    CREATE TABLE posts (
      id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
      user_id INT UNSIGNED NOT NULL,
      body LONGTEXT,
      KEY idx_user (user_id),
      CONSTRAINT fk_posts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
    );
  `;
  const result = parseSqlSchema(sql);

  it("crea las tablas y columnas", () => {
    expect(result.tables.map((table) => table.name)).toEqual(["users", "posts"]);
    expect(fieldOf(result, "users", "id")).toMatchObject({ type: "id", isPrimary: true, autoIncrement: true });
    expect(fieldOf(result, "users", "email")).toMatchObject({ type: "varchar", isUnique: true, nullable: false });
    expect(fieldOf(result, "users", "status")).toMatchObject({ type: "enum", enumValues: ["active", "banned"], defaultValue: "'active'" });
    expect(fieldOf(result, "users", "is_admin")).toMatchObject({ type: "boolean", defaultValue: "0" });
    expect(fieldOf(result, "users", "created_at")).toMatchObject({ type: "timestamp", nullable: true, defaultValue: "CURRENT_TIMESTAMP" });
    expect(fieldOf(result, "posts", "id")).toMatchObject({ type: "bigserial", isPrimary: true });
    expect(fieldOf(result, "posts", "user_id")).toMatchObject({ type: "integer", isIndexed: true });
    expect(fieldOf(result, "posts", "body")).toMatchObject({ type: "longtext", nullable: true });
  });

  it("crea las relaciones", () => {
    expect(relationNames(result)).toEqual(["posts.user_id->users.id 1:N"]);
    expect(result.relations[0].onDelete).toBe("CASCADE");
    expect(result.warnings).toEqual([]);
  });

  it("coloca las tablas sin solaparse", () => {
    const [users, posts] = result.tables;
    expect(users.x !== posts.x || users.y !== posts.y).toBe(true);
  });
});

describe("parseSqlSchema — PostgreSQL", () => {
  it("entiende pg_dump con secuencias, tipos enum y ALTER TABLE", () => {
    const sql = `
      CREATE TYPE public.mood AS ENUM ('sad', 'ok', 'happy');
      CREATE TABLE public.people (
          id integer NOT NULL,
          name character varying(100) NOT NULL,
          current_mood public.mood DEFAULT 'ok'::public.mood,
          born timestamp without time zone,
          meta jsonb DEFAULT '{}'::jsonb,
          uid uuid DEFAULT gen_random_uuid()
      );
      CREATE SEQUENCE public.people_id_seq AS integer START WITH 1;
      ALTER TABLE ONLY public.people ALTER COLUMN id SET DEFAULT nextval('public.people_id_seq'::regclass);
      CREATE TABLE public.pets (
          id bigint GENERATED BY DEFAULT AS IDENTITY,
          owner_id integer,
          kind text CHECK (kind IN ('dog', 'cat'))
      );
      ALTER TABLE ONLY public.people ADD CONSTRAINT people_pkey PRIMARY KEY (id);
      ALTER TABLE ONLY public.pets ADD CONSTRAINT pets_pkey PRIMARY KEY (id);
      ALTER TABLE ONLY public.pets
          ADD CONSTRAINT pets_owner_fk FOREIGN KEY (owner_id) REFERENCES public.people(id) ON DELETE SET NULL;
      CREATE UNIQUE INDEX people_name_idx ON public.people USING btree (name);
      ALTER TABLE public.people OWNER TO postgres;
    `;
    const result = parseSqlSchema(sql);
    expect(fieldOf(result, "people", "id")).toMatchObject({ type: "id", isPrimary: true });
    expect(fieldOf(result, "people", "name")).toMatchObject({ type: "varchar", isUnique: true });
    expect(fieldOf(result, "people", "current_mood")).toMatchObject({ type: "enum", enumValues: ["sad", "ok", "happy"], defaultValue: "'ok'" });
    expect(fieldOf(result, "people", "born")).toMatchObject({ type: "timestamp" });
    expect(fieldOf(result, "people", "meta")).toMatchObject({ type: "jsonb", defaultValue: "'{}'" });
    expect(fieldOf(result, "people", "uid")).toMatchObject({ type: "uuid", defaultValue: "gen_random_uuid()" });
    expect(fieldOf(result, "pets", "id")).toMatchObject({ type: "bigserial", isPrimary: true });
    expect(fieldOf(result, "pets", "kind")).toMatchObject({ type: "enum", enumValues: ["dog", "cat"] });
    expect(relationNames(result)).toEqual(["pets.owner_id->people.id 1:N"]);
    expect(result.relations[0].onDelete).toBe("SET NULL");
  });
});

describe("parseSqlSchema — SQL Server", () => {
  it("entiende IDENTITY, corchetes, GO y defaults entre parentesis", () => {
    const sql = `
      CREATE TABLE [dbo].[Customers](
        [Id] [int] IDENTITY(1,1) NOT NULL,
        [Name] [nvarchar](max) NOT NULL,
        [Active] [bit] NOT NULL CONSTRAINT [DF_Active] DEFAULT ((1)),
        [CreatedAt] [datetime2](7) NOT NULL DEFAULT (getdate()),
        [Token] [uniqueidentifier] NULL,
        CONSTRAINT [PK_Customers] PRIMARY KEY CLUSTERED ([Id] ASC)
      )
      GO
      CREATE TABLE [dbo].[Orders](
        [Id] [int] IDENTITY(1,1) NOT NULL PRIMARY KEY,
        [CustomerId] [int] NOT NULL
      )
      GO
      ALTER TABLE [dbo].[Orders] WITH CHECK ADD CONSTRAINT [FK_Orders_Customers] FOREIGN KEY([CustomerId])
      REFERENCES [dbo].[Customers] ([Id])
      GO
      CREATE NONCLUSTERED INDEX [IX_Orders_CustomerId] ON [dbo].[Orders] ([CustomerId] ASC)
      GO
    `;
    const result = parseSqlSchema(sql);
    expect(fieldOf(result, "Customers", "Id")).toMatchObject({ type: "id", isPrimary: true });
    expect(fieldOf(result, "Customers", "Name")).toMatchObject({ type: "text" });
    expect(fieldOf(result, "Customers", "Active")).toMatchObject({ type: "boolean", defaultValue: "1" });
    expect(fieldOf(result, "Customers", "CreatedAt")).toMatchObject({ type: "datetime", defaultValue: "getdate()" });
    expect(fieldOf(result, "Customers", "Token")).toMatchObject({ type: "uuid", nullable: true });
    expect(fieldOf(result, "Orders", "CustomerId")).toMatchObject({ isIndexed: true });
    expect(relationNames(result)).toEqual(["Orders.CustomerId->Customers.Id 1:N"]);
  });
});

describe("parseSqlSchema — casos especiales", () => {
  it("detecta relaciones 1:1 por FK unica y avisa de tablas desconocidas", () => {
    const result = parseSqlSchema(`
      CREATE TABLE users (id INT PRIMARY KEY);
      CREATE TABLE profiles (id INT PRIMARY KEY, user_id INT UNIQUE REFERENCES users(id), team_id INT REFERENCES teams(id));
    `);
    expect(relationNames(result)).toEqual(["profiles.user_id->users.id 1:1"]);
    expect(result.warnings.some((warning) => warning.includes("teams"))).toBe(true);
  });

  it("referencia a la PK cuando no se indican columnas", () => {
    const result = parseSqlSchema("CREATE TABLE a (id INT PRIMARY KEY); CREATE TABLE b (a_id INT REFERENCES a);");
    expect(relationNames(result)).toEqual(["b.a_id->a.id 1:N"]);
  });

  it("no confunde una columna llamada key con un indice", () => {
    const result = parseSqlSchema("CREATE TABLE settings (`key` VARCHAR(50) NOT NULL, value TEXT, KEY idx_key (`key`));");
    expect(fieldOf(result, "settings", "key")).toMatchObject({ type: "varchar", isIndexed: true });
    expect(fieldOf(result, "settings", "value")).toMatchObject({ type: "text" });
  });

  it("conserva claves primarias compuestas con aviso", () => {
    const result = parseSqlSchema(`
      CREATE TABLE a (id INT PRIMARY KEY);
      CREATE TABLE b (id INT PRIMARY KEY);
      CREATE TABLE a_b (a_id INT NOT NULL REFERENCES a(id), b_id INT NOT NULL REFERENCES b(id), PRIMARY KEY (a_id, b_id));
    `);
    expect(fieldOf(result, "a_b", "a_id").isPrimary).toBe(true);
    expect(fieldOf(result, "a_b", "b_id").isPrimary).toBe(true);
    expect(relationNames(result)).toEqual(["a_b.a_id->a.id 1:N", "a_b.b_id->b.id 1:N"]);
    expect(result.warnings.some((warning) => warning.includes("compuesta"))).toBe(true);
  });

  it("avisa de tipos desconocidos y devuelve vacio con texto que no es DDL", () => {
    expect(parseSqlSchema("SELECT * FROM users;").tables).toEqual([]);
    const result = parseSqlSchema("CREATE TABLE t (geo SDO_GEOMETRY);");
    expect(fieldOf(result, "t", "geo").type).toBe("text");
    expect(result.warnings[0]).toContain("SDO_GEOMETRY");
  });
});

describe("round-trip: generar SQL y volver a importarlo", () => {
  const base = createDefaultProject(normalizeTables);
  const users = base.tables[0];
  const posts = base.tables[1];
  const tags: Table = {
    id: "tbl_tags",
    name: "tags",
    x: 0,
    y: 0,
    fields: [
      normalizeField({ id: "fld_tags_id", name: "id", type: "id", nullable: false, isPrimary: true, isUnique: true, autoIncrement: true, isIndexed: true }),
      normalizeField({ id: "fld_tags_kind", name: "kind", type: "enum", enumValues: ["a", "b"], nullable: false, isPrimary: false, isUnique: false, autoIncrement: false, isIndexed: false, defaultValue: "a" }),
      normalizeField({ id: "fld_tags_n", name: "weight", type: "integer", nullable: true, isPrimary: false, isUnique: false, autoIncrement: false, isIndexed: true, defaultValue: "10" }),
    ],
  };
  const junction = buildJunction([users, posts, tags], { fromTableId: posts.id, fromFieldId: posts.fields[0].id, toTableId: tags.id, toFieldId: tags.fields[0].id });
  if (!junction) throw new Error("junction");
  const project = { tables: [users, posts, tags, junction.table], relations: [...base.relations, ...junction.relations] };

  it.each(["mysql", "postgresql", "sqlserver"] as const)("%s conserva tablas, columnas y relaciones", (dialect) => {
    const result = parseSqlSchema(generateSql(project, dialect));
    expect(result.tables.map((table) => table.name).sort()).toEqual(["posts", "posts_tags", "tags", "users"]);
    expect(relationNames(result).sort()).toEqual(
      ["posts.user_id->users.id 1:N", "posts_tags.posts_id->posts.id 1:N", "posts_tags.tags_id->tags.id 1:N"].sort(),
    );
    expect(fieldOf(result, "tags", "id")).toMatchObject({ type: "id", isPrimary: true });
    expect(fieldOf(result, "tags", "kind")).toMatchObject({ type: "enum", enumValues: ["a", "b"], defaultValue: "'a'" });
    expect(fieldOf(result, "tags", "weight")).toMatchObject({ nullable: true, isIndexed: true, defaultValue: "10" });
    expect(fieldOf(result, "users", "email").isUnique).toBe(true);
    expect(fieldOf(result, "users", "id").type).toBe("uuid");
    expect(result.warnings).toEqual([]);
  });
});
